export const chineseCharacterAliases: Record<string, readonly string[]> = {};
export const normalizeChineseCharacterName = (value: string): string => value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^\p{L}\p{N}]+/gu," ").trim();
export const normalizeChineseCharacterCode = (value: string): string => value.normalize("NFKC").toUpperCase().replace(/<>|[\u25C6\u2662]/g,"◇").replace(/-DZR-/g,"-◇ZR-").replace(/[\u2010-\u2015\u2212]/g,"-").replace(/\s+/g,"");
export type ChineseCharacterCard = { code: string; setId?: string };
export function getChineseCardCharacters(card: ChineseCharacterCard): string[] {
 const code=normalizeChineseCharacterCode(card.code);
 const scoped=card.setId?chineseCharacterOverrides[card.setId]:undefined;
 const names=scoped?.[code]??chineseCharacterMap[code]??[];
 return [...new Set(names.map(name=>name.trim()).filter(Boolean))];
}
export function matchesChineseCharacter(card: ChineseCharacterCard, query: string): boolean {
 const words=normalizeChineseCharacterName(query).split(" ").filter(Boolean);if(!words.length)return true;
 const names=getChineseCardCharacters(card);
 const text=names.flatMap(name=>[name,...(chineseCharacterAliases[name]??[])]).map(normalizeChineseCharacterName).join(" ");
 return words.every(word=>text.includes(word));
}
